#!/usr/bin/env node
// Builds dev/theme.css from Home Assistant's own theme token files, so the dev preview uses HA's real
// colours, type scale, radii, spacing and shadows. Needs a checkout of home-assistant/frontend
// (default ~/Projects/ha-frontend-reference; pass another path as the first argument).
// The tokens are Apache-2.0 licensed design values from https://github.com/home-assistant/frontend.
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const root = process.argv[2] ?? join(homedir(), "Projects", "ha-frontend-reference");
const theme = join(root, "src", "resources", "theme");

/** The body of `export const <name> = css\`...\`` in a file. */
function block(file, name) {
  const text = readFileSync(join(theme, file), "utf8");
  const m = new RegExp(`export const ${name} = css\`([\\s\\S]*?)\`;`).exec(text);
  if (!m) throw new Error(`${name} not found in ${file}`);
  return m[1];
}
const dark = (css) => css.replace(/(^|\n)(\s*)html\s*\{/g, '$1$2html[data-theme="dark"] {');
const tag = (file, name, wrap = (c) => c) => `/* ${name} (${file}) */\n${wrap(block(file, name))}`;

const light = [
  ["color/core.globals.ts", "coreColorStyles"],
  ["color/color.globals.ts", "colorStyles"],
  ["color/semantic.globals.ts", "semanticColorStyles"],
  ["core.globals.ts", "coreStyles"],
  ["typography.globals.ts", "typographyStyles"],
  ["semantic.globals.ts", "semanticStyles"],
].map(([f, n]) => tag(f, n));
const darkBlocks = [
  ["color/color.globals.ts", "darkColorStyles"],
  ["color/semantic.globals.ts", "darkSemanticColorStyles"],
  ["semantic.globals.ts", "darkSemanticStyles"],
].map(([f, n]) => tag(f, n, dark));

writeFileSync(
  new URL("../../dev/theme.css", import.meta.url),
  `/* Generated by scripts/dev/make-theme.mjs from Home Assistant's frontend theme files. Do not edit. */\n${[...light, ...darkBlocks].join("\n")}\n`,
);
console.log("wrote dev/theme.css from", root);
